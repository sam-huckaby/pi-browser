import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { getCapabilities, getCellDimensions, setCapabilities, setCellDimensions, TuiAltScreen } from "@earendil-works/pi-tui";
import { DreamChromiumBackend } from "../src/dream/backend.ts";
import type { DreamFrame, DreamResult, Point } from "../src/dream/types.ts";
import { DreamView } from "../src/ui/dream-view.ts";
import { InspectionSurface } from "../src/ui/inspection-surface.ts";
import type { Theme } from "@earendil-works/pi-coding-agent";
import { VirtualTerminal } from "./virtual-terminal.ts";

const theme = { fg: (_color: string, text: string) => text, bold: (text: string) => text } as unknown as Theme;
const url = process.argv[2] ?? "http://127.0.0.1:4174";
const directory = fileURLToPath(new URL("../artifacts/dream-demo/", import.meta.url));
const caps = { ...getCapabilities() }, cells = { ...getCellDimensions() };
setCapabilities({ images: "kitty", trueColor: true, hyperlinks: false });
setCellDimensions({ widthPx: 10, heightPx: 20 });
const backend = new DreamChromiumBackend();
const terminal = new VirtualTerminal();
const tui = new TuiAltScreen(terminal);
let view: DreamView | undefined;
let result: DreamResult | undefined;
let latest!: DreamFrame;
try {
  const original = await backend.open(url); latest = original;
  view = new DreamView(original, { open: (...args) => backend.open(...args), close: () => backend.close(), apply: async (...args) => { latest = await backend.apply(...args); return latest; } }, tui, theme, new AbortController(), (value) => { result = value; });
  tui.start();
  const overlay = tui.showOverlay(view, { width: "100%", maxHeight: "100%", margin: 1, anchor: "top-left" });
  tui.renderNow(true);
  const bounds = overlay.getBounds()!;
  const surface = new InspectionSurface(original.snapshot, () => terminal.rows - 7, 3);
  surface.render(bounds.width);
  const placement = surface.placement!;
  const cell = (point: Point) => ({
    x: bounds.col + placement.left + Math.floor(point.x / original.snapshot.viewport.width * placement.widthPx / placement.cell.widthPx),
    y: bounds.row + placement.top + Math.floor(point.y / original.snapshot.viewport.height * placement.heightPx / placement.cell.heightPx),
  });
  const idle = async () => { await view!.whenIdle(); tui.renderNow(true); };
  const click = async (point: Point, double = false) => { const at = cell(point); terminal.click(at.x, at.y); if (double) terminal.click(at.x, at.y); await idle(); };
  const pasteText = async (text: string) => { terminal.onInput?.(`\u001b[200~${text}\u001b[201~`); terminal.onInput?.("\r"); await idle(); };
  const drag = async (from: Point, to: Point) => {
    const a = cell(from), b = cell(to);
    terminal.onInput?.(`\u001b[<0;${a.x + 1};${a.y + 1}M`);
    terminal.onInput?.(`\u001b[<32;${b.x + 1};${b.y + 1}M`);
    terminal.onInput?.(`\u001b[<0;${b.x + 1};${b.y + 1}m`);
    await idle();
  };
  await mkdir(directory, { recursive: true });
  await writeFile(`${directory}/before.png`, original.snapshot.png);
  await click({ x: 150, y: 188 });
  await writeFile(`${directory}/selected.png`, latest.snapshot.png);
  await click({ x: 155, y: 195 }, true);
  await pasteText("Make space for\nwhat’s next.");
  await click({ x: 170, y: 430 });
  terminal.onInput?.("\u001b[99;9u"); terminal.onInput?.("\u001b[118;9u"); await idle();
  const button = latest.state.selected!.bounds;
  await drag({ x: button.x + button.width / 2, y: button.y + button.height / 2 }, { x: 440, y: 430 });
  const moved = latest.state.selected!.bounds;
  await click({ x: moved.x + 90, y: moved.y + 26 }, true);
  await pasteText("Explore the vision");
  await drag({ x: 780, y: 180 }, { x: 744, y: 180 });
  terminal.onInput?.("\u0011"); await view.whenIdle();
  if (!result || result.canceled) throw new Error("The native Dream demo did not finish.");
  await writeFile(`${directory}/goal.png`, result.snapshot.png);
  await writeFile(`${directory}/changes.json`, JSON.stringify(result.state.changes, null, 2));
  await writeFile(`${directory}/index.html`, `<!doctype html><html><head><meta charset="utf-8"><title>Dream demo — before and goal</title><style>
body{margin:0;padding:30px;background:#101321;color:#f5f4ff;font:16px system-ui}h1{font-size:26px;margin:0 0 10px}p{color:#b8b6cd;line-height:1.5}nav{margin:24px 0}button{border:1px solid #6d5eaa;border-radius:8px;background:#252039;color:#e7ddff;padding:10px 16px;margin-right:10px;font:600 14px system-ui;cursor:pointer}button.active{background:#7954e8;border-color:#7954e8;color:#fff}img{display:block;width:min(100%,1280px);border:1px solid #514968;border-radius:12px;background:white}.note{font-size:13px}</style></head><body>
<h1>Dream — from the page you have to the page you want</h1><p>Real Chromium screenshots, generated by Pi’s native mouse/keyboard input path.<br>Rewritten headline · duplicated and repositioned CTA · edited duplicate text · shifted card.</p>
<nav><button onclick="show('before',this)">Original page</button><button onclick="show('selected',this)">DOM selection</button><button class="active" onclick="show('goal',this)">Finished goal</button></nav>
<img id="frame" src="goal.png" alt="Finished Dream goal"><p class="note">Screenshot-based editing, not source-code changes. This gallery is a static result viewer, not the Dream editor.</p>
<script>function show(name,button){document.getElementById('frame').src=name+'.png';document.getElementById('frame').alt=name;document.querySelectorAll('button').forEach(b=>b.classList.remove('active'));button.classList.add('active')}</script></body></html>`);
  console.log(`Saved ${result.state.changes.length} native-input edits and screenshots to ${directory}\nView: ${url}/result`);
  overlay.hide();
} finally {
  view?.dispose(); tui.stop(); await backend.close(); setCapabilities(caps); setCellDimensions(cells);
}
